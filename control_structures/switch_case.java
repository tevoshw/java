package control_structures;

public class switch_case {
    public static void main(String[] args) {
        char x = 'A';

    switch (x)
    {
    case 'A':
        System.out.println("A");
        break;

    case 'B':
        System.out.println("B");
        break;

    default:
        System.out.println("Other than A and B");
        break;
    }
    
    }
    
}
