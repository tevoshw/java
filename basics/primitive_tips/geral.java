package basics.primitive_tips;

public class geral {
    public static void main(String[] args) {
        
        // INT 
        int n1 = 10;
        System.out.println(n1);
        
        // FLOAT
        float n2 = 10.5f; // ITS NECESSARY TO USE THE F IN THE FINAL
        System.out.println(n2);

        // CHAR 
        char n3 = 'a'; // IN CHAR WE USE SIMPLE ASPAS
        System.out.println(n3);

        // STRING
        String n4 = "Hello World"; // IN STRING WE USE DOUBLE ASPAS
        System.out.println(n4);


    }
}
